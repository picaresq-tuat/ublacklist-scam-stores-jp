def test_probe_non200_for_400():
    stub = StubFetch({"https://shop.example/": 400})
    p = probe_domain("shop.example", fetch_fn=stub)
    assert p.verdict == "non200"
    assert p.status == 400


@pytest.mark.parametrize("status", [301, 403, 404, 410, 500, 503])
def test_probe_non200_for_every_non_200_status(status):
    stub = StubFetch({"https://shop.example/": status})
    assert probe_domain("shop.example", fetch_fn=stub).verdict == "non200"


def test_probe_keeps_ok_when_body_discarded():
    """200 + 添付 (discarded) は非 HTML でも証拠として扱う (features と同基準)。"""
    stub = StubFetch({"https://shop.example/": (200, True)})
    p = probe_domain("shop.example", fetch_fn=stub)
