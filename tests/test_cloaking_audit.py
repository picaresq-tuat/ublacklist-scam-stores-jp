class FakeGitops:
    def __init__(self, *, changes=True, pr=None):
        self.calls = []
        self.branch = ""
        self._changes = changes
        self._pr = pr or {"number": 9, "url": "https://github.com/o/r/pull/9"}

    def branch_name(self, night):
        return f"nightly/{night}"

    def ensure_branch(self, repo, branch):
        self.calls.append(("ensure_branch", branch))
        self.branch = branch
        return branch

    def git(self, repo, *args, check=True):
        self.calls.append(("git", *args))

    def has_changes(self, repo):
        return self._changes

    def push(self, repo, branch):
        self.calls.append(("push", branch))

    def open_pr(self, **kw):
        self.calls.append(("open_pr", kw))
        return self._pr


def test_push_pr_commits_and_opens_pr(tmp_path, monkeypatch):
    fake = FakeGitops()
    monkeypatch.setattr(cloaking_audit, "gitops", fake)
    monkeypatch.setenv("GITHUB_TOKEN", "ghp_FAKE")
    out = cloaking_audit.push_pr(
        repo_dir=tmp_path,
        owner_repo="owner/name",
        night="2026-10-12",
        body="BODY",
        rel_path="cloaking_detected/uBlacklist.txt",
        message="cloaking 監査 2026-10-12: -3 件",
    )
    assert out["number"] == 9
    kinds = [c[0] for c in fake.calls]
    assert kinds == ["ensure_branch", "git", "git", "push", "open_pr"]
    assert ("git", "add", "--", "cloaking_detected/uBlacklist.txt") in fake.calls
    pr_call = next(c for c in fake.calls if c[0] == "open_pr")[1]
    assert pr_call["head"] == "nightly/2026-10-12"
    assert pr_call["body"] == "BODY"
    assert pr_call["base"] == "main"
    assert "ghp_FAKE" not in pr_call["body"] + pr_call["title"] + pr_call["head"]


