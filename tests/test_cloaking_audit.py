"""P9c: 既存 cloaking リストの偽陽性 (非 200) 検知と剪定の RED テスト。

ネットワークは fetch 注入でスタブする。
検証したいこと:
  * 通常取得が 200 以外を返したら「偽陽性」= 除外候補 (feature 側の cloaking 判定と同じ基準)
  * 200 + 添付/非 HTML (discarded) は証拠として残す (除外しない)
  * https が失敗しても http が 200 なら生存 (到達不能ではない)
  * 両スキーム失敗は unreachable (既定では除外しない / --include-unreachable で除外)
  * 剪定後もヘッダ・常設正規表現・セクション見出しは必ず残り validate() を通る
  * dry-run はファイルを書かない
"""

from __future__ import annotations

